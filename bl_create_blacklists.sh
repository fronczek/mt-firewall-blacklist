#!/bin/bash

# w debianie zamienic mawk na 
# apt-get install gawk

saveTo=/var/www
now=$(date);
host=$(hostname);

echo "# Generated by $host on $now" > $saveTo/mtbl_dshield.rsc
echo "/ip firewall address-list" >> $saveTo/mtbl_dshield.rsc
wget -q -O - http://feeds.dshield.org/block.txt | awk --posix '/^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.0\t/ { print "add list=BlackList_dshield address=" $1 "/24 timeout=30d comment=DShield";}' >> $saveTo/mtbl_dshield.rsc

echo "# Generated by $host on $now" > $saveTo/mtbl_spamhaus.rsc
echo "/ip firewall address-list" >> $saveTo/mtbl_spamhaus.rsc
wget -q -O - http://www.spamhaus.org/drop/drop.txt | awk --posix '/[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\// { print "add list=BlackList_SpamHausD address=" $1 " timeout=30d comment=SpamHausDrop";}' >> $saveTo/mtbl_spamhaus.rsc

echo "# Generated by $host on $now" > $saveTo/mtbl_spamhause.rsc
echo "/ip firewall address-list" >> $saveTo/mtbl_spamhause.rsc
wget -q -O - http://www.spamhaus.org/drop/edrop.txt | awk --posix '/[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\// { print "add list=BlackList_SpamHaudDExt address=" $1 " timeout=30d comment=SpamHauseDrop";}' >> $saveTo/mtbl_spamhause.rsc

echo "# Generated by $host on $now" > $saveTo/mtbl_firehol.rsc
echo "/ip firewall address-list" >> $saveTo/mtbl_firehol.rsc
wget -q -O - https://raw.githubusercontent.com/ktsaou/blocklist-ipsets/master/firehol_level1.netset | awk --posix '/^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}/ { print "add list=BlackList_firehol address=" $1 " timeout=30d comment=Firehol";}' >> $saveTo/mtbl_firehol.rsc
